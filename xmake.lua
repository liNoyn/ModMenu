add_rules("mode.release", "mode.debug")
set_project("ModMenu")
local menu_version = "0.1.0"
set_version(menu_version)
add_defines('MODMENU_VERSION="' .. menu_version .. '"')
set_languages("c++20")
set_encodings("utf-8")
set_runtimes("MT")
add_requires("imgui v1.91.9", {configs={shared=false, win32=true, dx11=true}})
add_requires("minhook 1.3.4", {configs={shared=false}})
add_requires("nlohmann_json v3.12.0")
target("ModMenu")
    set_kind("shared")
    add_files("src/*.cpp")
    add_includedirs("include")
    add_defines("NOMINMAX", "WIN32_LEAN_AND_MEAN", "UNICODE", "_UNICODE")
    add_packages("imgui", "minhook", "nlohmann_json")
    add_syslinks("user32", "gdi32", "shell32", "ole32", "windowscodecs", "d3d11", "d3d12", "dxgi", "version", "winhttp", "imm32", "dwmapi")
    after_build(function(t)
        os.mkdir("dist/ModMenu")
        os.cp(t:targetfile(), "dist/ModMenu/")
        local json = import("core.base.json")
        local manifest = json.loadfile("manifest.json")
        manifest.version = t:version()
        json.savefile("dist/ModMenu/manifest.json", manifest)
        os.cp("THIRD_PARTY_NOTICES.txt", "dist/ModMenu/")
        os.cp("assets", "dist/ModMenu/")
        os.cp("README*.md", "dist/ModMenu/")
        os.cp("LICENSE", "dist/ModMenu/")
    end)
target("ModelTests")
    set_default(false)
    set_kind("binary")
    add_files("tests/ModelTests.cpp", "src/Model.cpp", "src/MenuDefinition.cpp", "src/I18n.cpp")
    add_includedirs("include")
    add_defines("NOMINMAX", "WIN32_LEAN_AND_MEAN", "UNICODE", "_UNICODE")
    add_packages("nlohmann_json")
    add_syslinks("user32", "shell32", "winhttp")

target("Preview")
    set_default(false)
    set_kind("binary")
    add_files("tests/Preview.cpp", "src/Assets.cpp", "src/Ui.cpp", "src/Model.cpp", "src/Graphics.cpp", "src/NativeBridge.cpp", "src/MenuDefinition.cpp", "src/I18n.cpp")
    add_includedirs("include")
    add_defines("NOMINMAX", "WIN32_LEAN_AND_MEAN", "UNICODE", "_UNICODE", "BE_PREVIEW")
    add_packages("imgui", "minhook", "nlohmann_json")
    add_ldflags("/subsystem:windows")
    add_syslinks("user32", "gdi32", "shell32", "ole32", "windowscodecs", "d3d11", "d3d12", "dxgi", "version", "winhttp", "imm32", "dwmapi")
